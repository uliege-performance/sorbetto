from sorbetto.ranking._constraint_linear_homogeneous_on_importance import (
    ConstraintLinearHomogeneousOnImportance,
)


class ConstraintImportanceAdaptedToClassPriors(ConstraintLinearHomogeneousOnImportance):
    """
    This class represents the homogeneous linear constraint on importance values:

    .. math::
        \\pi_- I(tn) - \\pi_- I(fp) - \\pi_+ I(fn) + \\pi_+ I(tp) = 0

    where :math:`(\\pi_-, \\pi_+)` are the class priors.

    The corresponding ranking scores include:
    the accuracy,
    the macro-recall (a.k.a. balanced accuracy),
    the true negative rate,
    the true positive rate,
    the standardized negative predictive value :cite:t:`Heston2011Standardizing`,
    the standardized positive predictive value :cite:t:`Heston2011Standardizing`,
    and the skew-insensitive version of F-one :cite:t:`Flach2003TheGeometry`.

    It has been shown in :cite:t:`Pierard2026TheOptimal-arxiv` that linearly
    interpolating the importances in this plane leads to shortest path
    (geodesics) in terms of Kendall's distance :math:`d_\\tau=\\frac{1-\\tau}{2}`.
    In other words, if :math:`I_A` and :math:`I_B` satisfy this constraint and
    if :math:`I = w_A I_A + w_B I_B` with :math:`w_A\\ge0`, :math:`w_B\\ge0`,
    and :math:`w_A + w_B = 1`, then (assuming no tie)

    .. math::
        d_\\tau(R_{I_A};R_I) + d_\\tau(R_I;R_{I_B}) = d_\\tau(R_{I_A};R_{I_B})
        \\Leftrightarrow
        \\tau(R_{I_A};R_I) + \\tau(R_I;R_{I_B}) = 1 + \\tau(R_{I_A};R_{I_B})

    These shortest path correspond to weighted $f$-mean :math:`R_I` between
    :math:`R_{I_A}` and :math:`R_{I_B}` generated by some homography $f$.
    """

    def __init__(self, priorPos: float):
        assert isinstance(priorPos, float)
        assert priorPos >= 0.0
        assert priorPos <= 1.0
        self._priorPos = priorPos
        priorNeg = 1.0 - priorPos
        ConstraintLinearHomogeneousOnImportance.__init__(
            self, priorNeg, -priorNeg, -priorPos, priorPos
        )

    def __str__(self) -> str:
        priorPos = self._priorPos
        priorNeg = 1.0 - priorPos
        return "constraint: adapted to class priors ({:g},{:g})".format(
            priorNeg, priorPos
        )
