from sorbetto.ranking._constraint_linear_homogeneous_on_importance import (
    ConstraintLinearHomogeneousOnImportance,
)


class ConstraintImportanceAdaptedToPredictionRates(
    ConstraintLinearHomogeneousOnImportance
):
    """
    This class represents the homogeneous linear constraint on importance values:

    .. math::
        \\tau_- I(tn) - \\tau_+ I(fp) - \\tau_- I(fn) + \\tau_+ I(tp) = 0

    where :math:`(\\tau_-, \\tau_+)` are the prediction rates.

    The corresponding ranking scores include:
    the accuracy,
    the macro-precision,
    the negative predictive value,
    and the positive predictive value.

    Following a line of reasoning similar to that presented in
    :cite:t:`Pierard2026TheOptimal-arxiv`, it can be shown that linearly
    interpolating the importances in this plane leads to shortest path
    (geodesics) in terms of Kendall's distance :math:`d_\\tau=\\frac{1-\\tau}{2}`
    (:math:`\\tau` is Kendall's rank correlation).
    In other words, if :math:`I_A` and :math:`I_B` satisfy this constraint and
    if :math:`I = w_A I_A + w_B I_B` with :math:`w_A\\ge0`, :math:`w_B\\ge0`,
    and :math:`w_A + w_B = 1`, then (assuming no tie)

    .. math::
        d_\\tau(R_{I_A};R_I) + d_\\tau(R_I;R_{I_B}) = d_\\tau(R_{I_A};R_{I_B})
        \\Leftrightarrow
        \\tau(R_{I_A};R_I) + \\tau(R_I;R_{I_B}) = 1 + \\tau(R_{I_A};R_{I_B})

    These shortest path correspond to weighted $f$-mean :math:`R_I` between
    :math:`R_{I_A}` and :math:`R_{I_B}` generated by some homography $f$.
    """

    def __init__(self, ratePos: float):
        assert isinstance(ratePos, float)
        assert ratePos >= 0.0
        assert ratePos <= 1.0
        self._ratePos = ratePos
        rateNeg = 1.0 - ratePos
        ConstraintLinearHomogeneousOnImportance.__init__(
            self, rateNeg, -ratePos, -rateNeg, ratePos
        )

    def getRateNeg(self):
        return 1.0 - self._ratePos

    def getRatePos(self):
        return self._ratePos

    def __str__(self) -> str:
        ratePos = self._ratePos
        rateNeg = 1.0 - ratePos
        return "constraint: adapted to prediction rates ({:g},{:g})".format(
            rateNeg, ratePos
        )
